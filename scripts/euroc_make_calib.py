#!/usr/bin/env python3
"""Convert EuRoC MAV sensor.yaml files into MC-SLAM's Kalibr-style calibration.

EuRoC ships one sensor.yaml per sensor with T_BS (sensor -> body/IMU frame).
MC-SLAM expects a single file with:
  cam0/cam1:  intrinsics, distortion, resolution, and for cam1 T_cn_cnm1 = T_c1_c0
  imu:        noise densities / random walks and Tbc = T_B_C0 (cam0 -> body)

Usage: euroc_make_calib.py <sequence>/mav0 <output.yaml>
"""
import sys
from pathlib import Path

import numpy as np
import yaml


def load_sensor(path: Path) -> dict:
    text = path.read_text()
    # EuRoC files start with an OpenCV-style "%YAML:1.0" directive that PyYAML rejects.
    text = "\n".join(l for l in text.splitlines() if not l.startswith("%YAML"))
    return yaml.safe_load(text)


def t_bs(sensor: dict) -> np.ndarray:
    m = sensor["T_BS"]
    return np.array(m["data"], dtype=float).reshape(m["rows"], m["cols"])


def fmt_matrix(T: np.ndarray, indent: str) -> str:
    return "\n".join(f"{indent}- [{', '.join(f'{v:.16g}' for v in row)}]" for row in T)


def camera_block(name: str, cam: dict, T_cn_cnm1=None) -> str:
    assert cam["camera_model"] == "pinhole" and cam["distortion_model"] == "radial-tangential"
    lines = [f"{name}:"]
    if T_cn_cnm1 is not None:
        lines += ["  T_cn_cnm1:", fmt_matrix(T_cn_cnm1, "    ")]
    lines += [
        "  camera_model: pinhole",
        "  distortion_model: radtan",
        f"  intrinsics: [{', '.join(f'{v:.16g}' for v in cam['intrinsics'])}]",
        f"  distortion_coeffs: [{', '.join(f'{v:.16g}' for v in cam['distortion_coefficients'])}]",
        f"  resolution: [{cam['resolution'][0]}, {cam['resolution'][1]}]",
        f"  rostopic: /cam{name[-1]}/image_raw",
    ]
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 1
    mav0, out = Path(sys.argv[1]), Path(sys.argv[2])
    cam0, cam1, imu = (load_sensor(mav0 / s / "sensor.yaml") for s in ("cam0", "cam1", "imu0"))

    T_B_C0, T_B_C1 = t_bs(cam0), t_bs(cam1)
    T_C1_C0 = np.linalg.inv(T_B_C1) @ T_B_C0
    baseline = np.linalg.norm(T_C1_C0[:3, 3])

    body = "\n\n".join([
        camera_block("cam0", cam0),
        camera_block("cam1", cam1, T_C1_C0),
        "\n".join([
            "imu:",
            "  rostopic: /imu0",
            "  # Continuous-time noise densities and bias random walks (EuRoC imu0/sensor.yaml)",
            f"  acc_noise: {imu['accelerometer_noise_density']}",
            f"  gyr_noise: {imu['gyroscope_noise_density']}",
            f"  acc_walk: {imu['accelerometer_random_walk']}",
            f"  gyr_walk: {imu['gyroscope_random_walk']}",
            "  g_norm: 9.81",
            "  # T cam0 -> body (IMU) frame",
            "  Tbc:",
            fmt_matrix(T_B_C0, "    "),
        ]),
    ])
    header = (
        "%YAML:1.0\n"
        f"# Generated by scripts/euroc_make_calib.py from {mav0}\n"
        f"# Stereo baseline: {baseline:.4f} m\n"
    )
    out.write_text(header + body + "\n")
    print(f"wrote {out} (baseline {baseline:.4f} m)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
